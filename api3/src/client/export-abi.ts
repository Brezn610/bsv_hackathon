// Copies TreasuryGuard's ABI from the forge build into abi.ts, so the client (and the BSV side importing it) gets typed
// calls without running forge. Run after every interface change: forge build && node src/client/export-abi.ts
import { readFileSync, writeFileSync } from 'node:fs';

const artifact = JSON.parse(
  readFileSync(new URL('../../out/TreasuryGuard.sol/TreasuryGuard.json', import.meta.url), 'utf8')
) as { abi: unknown[] };

writeFileSync(
  new URL('abi.ts', import.meta.url),
  `// Generated by src/client/export-abi.ts from out/TreasuryGuard.sol/TreasuryGuard.json. Do not edit.\n` +
    `export const treasuryGuardAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`
);
console.log(`Wrote ${artifact.abi.length} ABI entries to src/client/abi.ts`);
